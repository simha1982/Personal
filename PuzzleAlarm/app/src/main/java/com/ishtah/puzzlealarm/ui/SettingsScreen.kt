@OptIn(ExperimentalMaterial3Api::class, ExperimentalLayoutApi::class)
@Composable
fun SettingsScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    val store = remember { SettingsStore.get(context) }
    val settings by store.settings.collectAsState()
    val puzzles = remember { PuzzleRepository(context.applicationContext) }
    val scope = rememberCoroutineScope()

    var provider by remember { mutableStateOf(settings.provider) }
    var apiKey by remember { mutableStateOf(settings.apiKey) }
    var model by remember { mutableStateOf(settings.model) }
    var baseUrl by remember { mutableStateOf(settings.baseUrl) }
    var showKey by remember { mutableStateOf(false) }
    var testing by remember { mutableStateOf(false) }
    var testPuzzle by remember { mutableStateOf<Puzzle?>(null) }
    var testError by remember { mutableStateOf<String?>(null) }

    fun saveText() = store.update { it.copy(provider = provider, apiKey = apiKey, model = model, baseUrl = baseUrl) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Settings") },
                navigationIcon = {
                    IconButton(onClick = { saveText(); onBack() }) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
            )
        },
    ) { padding ->
        Column(
            Modifier.fillMaxSize().padding(padding).verticalScroll(rememberScrollState()).padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            Section("AI puzzles")
            Text(
                "Puzzles are generated by AI using your own API key: Claude (Anthropic), OpenRouter, OpenAI, or any " +
                    "OpenAI-compatible server. If there's no key, no network, or no answer within 30 seconds, a built-in " +
                    "offline puzzle is used so the alarm can always be turned off.",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Text("Provider", style = MaterialTheme.typography.titleSmall)
            FlowRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                AiProvider.entries.forEach { p ->
                    FilterChip(
                        selected = provider == p,
                        onClick = { provider = p },
                        label = { Text(p.label) },
                    )
                }
            }
            OutlinedTextField(
                value = apiKey,
                onValueChange = { key ->
                    apiKey = key
                    // Pasting a key picks the matching provider (sk-ant-, sk-or-, sk-).
                    AiProvider.detect(key)?.let { detected ->
                        if (provider != AiProvider.CUSTOM || detected != AiProvider.OPENAI) provider = detected
                    }
                },
                label = { Text("${provider.label} API key") },
                placeholder = { Text(KEY_HINTS.getValue(provider)) },
                singleLine = true,
                visualTransformation = if (showKey) VisualTransformation.None else PasswordVisualTransformation(),
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                trailingIcon = { TextButton(onClick = { showKey = !showKey }) { Text(if (showKey) "Hide" else "Show") } },
                modifier = Modifier.fillMaxWidth(),
            )
            OutlinedTextField(
                value = model,
                onValueChange = { model = it },
                label = { Text("Model") },
                placeholder = { Text(provider.defaultModel.ifEmpty { "e.g. llama-3.3-70b" }) },
                supportingText = {
                    Text(
                        if (provider.defaultModel.isEmpty()) "Required for this provider"
                        else "Leave empty for ${provider.defaultModel}" +
                            if (provider == AiProvider.OPENROUTER) " (or e.g. openai/gpt-4o-mini)" else ""
                    )
                },
                singleLine = true,
                modifier = Modifier.fillMaxWidth(),
            )
            if (provider == AiProvider.CUSTOM) {
                OutlinedTextField(
                    value = baseUrl,
                    onValueChange = { baseUrl = it },
                    label = { Text("Base URL") },
                    placeholder = { Text("https://example.com/v1") },
                    supportingText = { Text("The part before /chat/completions") },
                    singleLine = true,
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Uri),
                    modifier = Modifier.fillMaxWidth(),
                )
            }
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                OutlinedButton(onClick = { saveText() }) { Text("Save") }
                OutlinedButton(
                    enabled = !testing,
                    onClick = {
                        saveText()
                        testing = true
                        scope.launch {
                            testPuzzle = puzzles.next()
                            testError = puzzles.lastError
                            testing = false
                        }
                    },
                ) { Text(if (testing) "Generating…" else "Try a puzzle") }
            }
            testPuzzle?.let { p ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                        Text(p.source.label, style = MaterialTheme.typography.labelMedium, color = MaterialTheme.colorScheme.primary)
                        Text(p.question, style = MaterialTheme.typography.bodyLarge)
                        Text("Answer: ${p.answer}", style = MaterialTheme.typography.bodySmall)
                        testError?.let {
                            Text("AI not used: $it", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.error)
                        }
                    }
                }
            }

            HorizontalDivider()
            Section("Waking up")
            Text("Difficulty", style = MaterialTheme.typography.titleSmall)
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Difficulty.entries.forEach { d ->
                    FilterChip(
                        selected = settings.difficulty == d,
                        onClick = { store.update { it.copy(difficulty = d) } },
                        label = { Text(d.label) },
                    )
                }
            }
            Text("Puzzles to solve before the alarm stops", style = MaterialTheme.typography.titleSmall)
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                (1..3).forEach { n ->
                    FilterChip(
                        selected = settings.puzzlesToSolve == n,
                        onClick = { store.update { it.copy(puzzlesToSolve = n) } },
                        label = { Text("$n") },
                    )
                }
            }
            OutlinedButton(onClick = {
                saveText()
                AlarmService.start(context, alarmId = TEST_ALARM_ID, isSnooze = false)
                context.startActivity(Intent(context, AlarmActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
            }) { Text("Ring a test alarm now") }

            HorizontalDivider()
            Section("Permissions")
            PermissionRows()
            Spacer(Modifier.height(24.dp))
        }
    }
}

private const val TEST_ALARM_ID = 0

private val KEY_HINTS = mapOf(
    AiProvider.ANTHROPIC to "sk-ant-…",
    AiProvider.OPENROUTER to "sk-or-…",
    AiProvider.OPENAI to "sk-…",
    AiProvider.CUSTOM to "API key",
)

@Composable
private fun Section(title: String) {
    Text(title, style = MaterialTheme.typography.titleMedium, color = MaterialTheme.colorScheme.primary)
}

@Composable
private fun PermissionRows() {
    val context = LocalContext.current
    val pkg = Uri.parse("package:${context.packageName}")

    val notificationsOk = Build.VERSION.SDK_INT < 33 ||
        ContextCompat.checkSelfPermission(context, Manifest.permission.POST_NOTIFICATIONS) == PackageManager.PERMISSION_GRANTED
    PermissionRow("Notifications", notificationsOk) {
        context.startActivity(
            Intent(Settings.ACTION_APP_NOTIFICATION_SETTINGS).putExtra(Settings.EXTRA_APP_PACKAGE, context.packageName)
        )
    }

    if (Build.VERSION.SDK_INT >= 34) {
        val ok = context.getSystemService(NotificationManager::class.java).canUseFullScreenIntent()
        PermissionRow("Full-screen alarm over lock screen", ok) {
            context.startActivity(Intent(Settings.ACTION_MANAGE_APP_USE_FULL_SCREEN_INTENT, pkg))
        }
    }

    if (Build.VERSION.SDK_INT >= 31) {
        PermissionRow("Exact alarms", AlarmScheduler.canScheduleExact(context)) {
            context.startActivity(Intent(Settings.ACTION_REQUEST_SCHEDULE_EXACT_ALARM, pkg))
        }
    }

    Text(
        "Tip: on some phones (Xiaomi, Oppo, Vivo, Samsung) also set battery usage for Puzzle Alarm to \"Unrestricted\" so alarms aren't delayed.",
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
    )
}

@Composable
private fun PermissionRow(name: String, granted: Boolean, onFix: () -> Unit) {
    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
        Text(name, modifier = Modifier.weight(1f))
        if (granted) {
            Text("Allowed", color = MaterialTheme.colorScheme.primary)
        } else {
            TextButton(onClick = onFix) { Text("Allow", color = MaterialTheme.colorScheme.error) }
        }
    }
}
